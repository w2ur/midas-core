def _with_clean_tail(
    stored_closes: list[float], fetched_closes: list[float], tail: int = 5
) -> tuple[list[dict], pd.DataFrame]:
    """Append `tail` rows on which the two series already agree.

    Every real split has one (24-62 rows), and detect_split requires it: a
    wholly-drifted overlap has no observable transition and fails closed.
    """
    base = len(fetched_closes)
    agreeing = [500.0 + i for i in range(tail)]
    return (
        _stored(stored_closes + agreeing),
        _frame(fetched_closes + agreeing),
    )


def test_detect_split_finds_a_single_constant_ratio():
    """CRWD's real signature: every pre-split row divided by the same factor
    (measured 0.0% spread across 552 rows), then a clean post-split run."""
    fetched_closes = [100.0 + i for i in range(15)]
    stored_closes = [c * 4.0 for c in fetched_closes]
    stored, fetched = _with_clean_tail(stored_closes, fetched_closes)
    assert detect_split(stored, fetched) == pytest.approx(4.0)


def test_detect_split_ignores_scattered_drift():
    """ALV.DE's real signature: many rows, each at its OWN distinct ratio,
    scattered a couple of percent around 1.0 — measured 4.20% spread across
    24 rows live. Rejected on materiality, exactly as the real ALV.DE
    fixture is: scatter centred on 1.0 leaves the anchor ratio inside the
    materiality floor, so there is no split-sized effect to apply."""
    ratios = [0.960 + 0.002 * i for i in range(15)]  # 15 distinct ratios
    fetched_closes = [100.0] * 15
    stored_closes = [f * r for f, r in zip(fetched_closes, ratios)]
    stored, fetched = _with_clean_tail(stored_closes, fetched_closes)
    assert detect_split(stored, fetched) is None


def test_detect_split_refuses_a_wide_scatter_that_never_forms_one_cluster():
    """The other half of scattered drift: ratios far enough from 1.0 to
    clear materiality, but spread so wide that walking back from the
    transition never assembles _MIN_DRIFTED_ROWS rows sharing one ratio."""
    ratios = [0.80 + 0.01 * i for i in range(15)]  # 0.80 .. 0.94
    fetched_closes = [100.0] * 15
    stored_closes = [f * r for f, r in zip(fetched_closes, ratios)]
    stored, fetched = _with_clean_tail(stored_closes, fetched_closes)
    assert abs(statistics.median(ratios) - 1.0) > 0.03  # clears materiality
    assert detect_split(stored, fetched) is None


